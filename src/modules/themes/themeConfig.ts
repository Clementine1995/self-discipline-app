export const getThemeConfig = (themeId: string) => {
  const normalizedThemeId = legacyThemeFallbacks[themeId as ThemeConfig['id']] ?? themeId;
  return themeConfigs.find((theme) => theme.id === normalizedThemeId) ?? themeConfigs[0];
};
